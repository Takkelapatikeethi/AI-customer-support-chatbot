CREATE TABLE IF NOT EXISTS company_support_faq (
 id VARCHAR(64) NOT NULL PRIMARY KEY,
 record JSON NOT NULL,
 access_level VARCHAR(32) GENERATED ALWAYS AS (JSON_UNQUOTE(JSON_EXTRACT(record, '$.accessLevel'))) STORED,
 is_active TINYINT GENERATED ALWAYS AS (JSON_EXTRACT(record, '$.isActive') = TRUE) STORED,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_faq_access_active (access_level, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
